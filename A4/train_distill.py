def detect_model_family(model_path: str) -> str:
    name = model_path.lower()
    if "llama" in name:
        return "llama"
    if "qwen" in name:
        return "qwen"
    try:
        config_path = Path(model_path) / "config.json"
        if config_path.exists():
            config = json.loads(config_path.read_text())
            arch       = " ".join(config.get("architectures", [])).lower()
            model_type = config.get("model_type", "").lower()
            if "llama" in arch or "llama" in model_type:
                return "llama"
            if "qwen" in arch or "qwen" in model_type:
                return "qwen"
    except Exception:
        pass
    LOGGER.warning(
        "Could not detect model family from '%s' — defaulting to 'qwen'", model_path
    )
    return "qwen"


def format_teacher_prompt(instruction: str, language: str) -> str:
    lang_name = LANG_NAMES.get(language.lower(), "English")
    return (
        f"You are an expert. Answer the following question in {lang_name}.\n"
        f"Think step by step before answering.\n\n"
        f"Write your reasoning inside <reasoning>...</reasoning> tags.\n"
        f"At the end, write your final answer as: #### ANSWER: (X) where X is the correct letter.\n\n"
        f"{instruction}"
    )



def setup_logger(level: str) -> None:
    numeric_level = getattr(logging, level.upper(), logging.INFO)
    logging.basicConfig(
        level=numeric_level,
        format="%(asctime)s | %(levelname)s | %(message)s",
        force=True,
    )


